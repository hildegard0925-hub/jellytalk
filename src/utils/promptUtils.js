export function buildMissionPrompt(
  missions,
  category
) {

  const rolePrompt =
    categoryRoles[category] || ''

  const currentMission =
    missions[0]

  const nextMissions =
    missions.slice(1)

  const randomMood =
    getRandomItem(
      moodPools[category] || []
    )

  const randomPersonality =
    getRandomItem(
      personalityPools
    )

  return `
${rolePrompt}

오늘 분위기:
${randomMood}

직원 성격:
${randomPersonality}

현재 상황에서:
${currentMission.prompt}

대화 중 자연스럽게 아래 상황들도 포함하세요:
${nextMissions
  .map(
    (mission) =>
      `- ${mission.text}`
  )
  .join('\n')}

규칙:
- 반드시 일본어로만 대화하세요.
- 너무 긴 문장은 피하세요.
- 사용자가 많이 말하도록 유도하세요.
- 너무 빨리 대화를 끝내지 마세요.
- 상황을 자연스럽게 이어가세요.
- 한 번의 응답으로 상황을 끝내지 마세요.
- 질문을 자주 하며 대화를 이어가세요.
- 사용자가 질문하거나 반응할 여지를 남겨두세요.
- 상황에 따라 새로운 화제를 자연스럽게 꺼내세요.
- 사용자를 같은 손님으로 계속 인식하세요.
- 필요하면 작은 문제나 새로운 상황이 자연스럽게 발생할 수 있습니다.
- 상황이 자연스러우면 가벼운 스몰토크를 시작하세요.
- 사용자가 일본 여행을 실제로 체험하는 느낌이 들도록 자연스럽게 대화를 이어가세요.
`
}

